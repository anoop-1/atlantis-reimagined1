#!/usr/bin/env node
/**
 * Compliance programme builder — 2026-08-20.
 * ─────────────────────────────────────────────────────────────────────────────
 * Reads the researched regime store and emits everything both render layers
 * need, the same arrangement build-depth-pages.mjs uses:
 *
 *   src/data/compliance-pages.json   consumed by src/components/CompliancePage
 *                                    (human visitors)
 *   scripts/compliance-routes.mjs    consumed by scripts/prerender.mjs
 *                                    (crawlers and AI retrievers — the layer
 *                                    that actually decides citation)
 *
 * A regime is REJECTED, not warned about, when its research is too thin to
 * render honestly. At this scale a padded regime becomes fourteen padded pages.
 *
 *   node scripts/build-compliance-pages.mjs
 *   node scripts/build-compliance-pages.mjs --dry
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { buildCompliancePages, renderHtml } from './compliance-pages.mjs';
import { sanitiseDeep, hasMarkdown } from './sanitise-content.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DRY = process.argv.includes('--dry');
const IN = join(__dirname, 'compliance-regimes.json');

if (!existsSync(IN)) {
  console.error(`Regime store not found: ${IN}`);
  console.error('Run the regime research workflow first.');
  process.exit(1);
}

const words = (s) => String(s ?? '').trim().split(/\s+/).filter(Boolean).length;

const raw = JSON.parse(readFileSync(IN, 'utf-8'));
const regimes = Array.isArray(raw) ? raw : raw.regimes || [];
console.log(`\nRegime store: ${regimes.length} regimes\n`);

// Markdown leaking into HTML-escaped fields renders as literal asterisks on the
// page — sanitise before anything is measured or rendered.
const cleaned = sanitiseDeep(regimes);
if (cleaned) console.log(`  sanitised markdown in ${cleaned} field(s)`);

const rejected = [];
const accepted = regimes.filter((r) => {
  const problems = [];
  if (!r || !r.slug) problems.push('no slug');
  if (!r?.shortName) problems.push('no shortName');
  if (words(r?.appliesTo) < 20) problems.push(`appliesTo ${words(r?.appliesTo)}w (min 20)`);
  if (words(r?.summary) < 40) problems.push(`summary ${words(r?.summary)}w (min 40)`);
  if (!(r?.requiredDocuments || []).length) problems.push('no requiredDocuments');
  if (!(r?.commonFindings || []).length) problems.push('no commonFindings');
  if (!r?.sources) problems.push('no sources');
  if (hasMarkdown(JSON.stringify(r || {}))) problems.push('markdown survived sanitise');
  if (problems.length) { rejected.push({ slug: r?.slug || '(unnamed)', problems }); return false; }
  return true;
});

for (const r of rejected) console.log(`  REJECT ${r.slug}: ${r.problems.join(' · ')}`);
console.log(`\n  ${accepted.length} regimes accepted, ${rejected.length} rejected\n`);

const built = buildCompliancePages(accepted);
console.log(`  ${built.pages.length} pages built · ${built.dropped} dropped by the similarity gate`);
console.log(`  ${Object.entries(built.counts).map(([k, v]) => `${k} ${v}`).join(' · ')}\n`);

if (DRY) {
  console.log('  --dry; nothing written.\n');
  process.exit(0);
}

// React layer: the structured data, minus the rendered HTML.
writeFileSync(join(__dirname, '..', 'src', 'data', 'compliance-pages.json'), JSON.stringify(built.pages, null, 1));

// Prerender layer: routes carrying the rendered static HTML.
const routes = built.pages.map((p) => ({
  path: p.slug,
  title: p.title,
  description: p.description,
  h1: p.h1,
  bodyContent: renderHtml(p),
}));
const mod = '// GENERATED by scripts/build-compliance-pages.mjs — do not edit by hand.\n'
  + '// Source of truth is scripts/compliance-regimes.json.\n'
  + `export const COMPLIANCE_ROUTES = ${JSON.stringify(routes, null, 1)};\n`;
writeFileSync(join(__dirname, 'compliance-routes.mjs'), mod);

console.log(`  src/data/compliance-pages.json   ${built.pages.length} pages (React layer)`);
console.log(`  scripts/compliance-routes.mjs    ${routes.length} routes (prerender layer)\n`);
