// Merges the dispatched content-agent batch outputs into the site's
// Practical NDT city pages: validates (word count >= 2000, slug uniqueness,
// forbidden-pattern scan), then generates:
//   - scripts/practical-ndt-routes.mjs (prerender static routes)
//   - src/data/practical-ndt-cities.ts (React layer data, same content)
//   - src/pages/practical-ndt-{slug}.tsx (thin wrapper pages)
//   - scripts/_practical-ndt-app-tsx-snippets.txt (App.tsx lines to insert)
import { readFileSync, writeFileSync, existsSync } from 'fs';

const SCRATCH = 'C:/Users/anuan/AppData/Local/Temp/claude/e--software-Atlantis/121cc0cc-ff27-4dc3-94e5-8cff90e8bd9c/scratchpad';
const batches = ['batchA', 'batchB', 'batchC', 'batchD', 'batchE1', 'batchE2', 'batchF1', 'batchF2'];

let all = [];
for (const b of batches) {
  const path = `${SCRATCH}/output-practical-ndt-${b}.json`;
  if (!existsSync(path)) {
    console.error(`MISSING: ${path}`);
    process.exit(1);
  }
  const items = JSON.parse(readFileSync(path, 'utf-8'));
  console.log(`${b}: ${items.length} items`);
  all = all.concat(items);
}

function wordCount(html) {
  const text = html.replace(/<[^>]+>/g, ' ').replace(/&[a-z]+;/g, ' ');
  return text.split(/\s+/).filter(Boolean).length;
}

const FORBIDDEN = [
  /\$\d/, // dollar amounts
  /anu\.anoop485/i,
  /Atlantis[^.]{0,60}(ISO 9712|PCN)[^.]{0,40}train/i,
  /Atlantis[^.]{0,60}API[^.]{0,40}train/i,
];

const seen = new Set();
const valid = [];
const rejected = [];
for (const item of all) {
  if (!item.slug || !item.city || !item.bodyContent) {
    rejected.push({ slug: item.slug, reason: 'missing required field' });
    continue;
  }
  if (seen.has(item.slug)) {
    rejected.push({ slug: item.slug, reason: 'duplicate slug' });
    continue;
  }
  const wc = wordCount(item.bodyContent);
  if (wc < 2000) {
    rejected.push({ slug: item.slug, reason: `only ${wc} words` });
    continue;
  }
  const hit = FORBIDDEN.find((re) => re.test(item.bodyContent));
  if (hit) {
    rejected.push({ slug: item.slug, reason: `forbidden pattern: ${hit}` });
    continue;
  }
  seen.add(item.slug);
  valid.push({ ...item, wordCount: wc });
}

console.log(`\n${valid.length}/${all.length} cities passed validation.`);
if (rejected.length) {
  console.log('\nREJECTED:');
  rejected.forEach((r) => console.log(`  ${r.slug}: ${r.reason}`));
}
if (valid.length === 0) {
  console.error('No valid cities — aborting.');
  process.exit(1);
}

// ── scripts/practical-ndt-routes.mjs ────────────────────────────────────
const routesJs = `// GENERATED by scripts/build-practical-ndt-routes.mjs — do not hand-edit.
// Source: merged content-agent batch output, ${valid.length} cities, ${new Date().toISOString()}.
export const PRACTICAL_NDT_ROUTES = ${JSON.stringify(
  valid.map((v) => ({
    path: `/practical-ndt-${v.slug}`,
    title: v.title,
    description: v.metaDescription,
    bodyContent: v.bodyContent,
  })),
  null,
  2
)};
`;
writeFileSync('scripts/practical-ndt-routes.mjs', routesJs);

// ── src/data/practical-ndt-cities.ts ────────────────────────────────────
const tsProfiles = valid.map((v) => ({
  slug: v.slug,
  city: v.city,
  region: v.region,
  title: v.title,
  metaDescription: v.metaDescription,
  contentHtml: v.bodyContent,
}));
const tsFile = `/**
 * Practical NDT City/Region Profiles — GENERATED, do not hand-edit.
 * Produced by scripts/build-practical-ndt-routes.mjs from the merged
 * content-agent batch output. Same content as scripts/practical-ndt-routes.mjs
 * (single source of truth — see project rule on keeping the two render
 * layers aligned).
 */
export interface PracticalNdtCityProfile {
  slug: string;
  city: string;
  region: string;
  title: string;
  metaDescription: string;
  contentHtml: string;
}

export const PRACTICAL_NDT_CITY_PROFILES: PracticalNdtCityProfile[] = ${JSON.stringify(tsProfiles, null, 2)};

export function getPracticalNdtCityProfile(slug: string): PracticalNdtCityProfile | undefined {
  return PRACTICAL_NDT_CITY_PROFILES.find((p) => p.slug === slug);
}
`;
writeFileSync('src/data/practical-ndt-cities.ts', tsFile);

// ── thin wrapper pages ──────────────────────────────────────────────────
function pascal(slug) {
  return slug.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
}

for (const v of valid) {
  const content = `import { PracticalNdtLocationPage } from '@/components/PracticalNdtLocationPage';
import { getPracticalNdtCityProfile } from '@/data/practical-ndt-cities';

export default function PracticalNdt${pascal(v.slug)}() {
  const profile = getPracticalNdtCityProfile('${v.slug}');
  if (!profile) return null;
  return <PracticalNdtLocationPage profile={profile} />;
}
`;
  writeFileSync(`src/pages/practical-ndt-${v.slug}.tsx`, content);
}

// ── App.tsx snippet file ────────────────────────────────────────────────
const lazyLines = valid
  .map((v) => `const PracticalNdt${pascal(v.slug)} = lazy(() => import("./pages/practical-ndt-${v.slug}"));`)
  .join('\n');
const routeLines = valid
  .map((v) => `                  <Route path="/practical-ndt-${v.slug}" element={<PracticalNdt${pascal(v.slug)} />} />`)
  .join('\n');
writeFileSync(
  'scripts/_practical-ndt-app-tsx-snippets.txt',
  `// LAZY IMPORTS — insert near other page lazy imports\n${lazyLines}\n\n// ROUTES — insert inside <Routes>\n${routeLines}\n`
);

console.log(`\nDone. ${valid.length} cities: routes.mjs, cities.ts, ${valid.length} wrapper pages, App.tsx snippet file written.`);
console.log('Slugs:', valid.map((v) => v.slug).join(', '));
