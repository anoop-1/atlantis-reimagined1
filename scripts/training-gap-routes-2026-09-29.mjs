import { readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://atlantisndt.com';
const load = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf-8'));

const PERSON = {
  '@type': 'Person',
  '@id': `${SITE}/#anoop-rayavarapu`,
  name: 'Anoop Rayavarapu',
  jobTitle: 'ASNT NDT Level III, Founder of Atlantis NDT',
  url: `${SITE}/authors/anoop-rayavarapu`,
};
const ORG = { '@type': 'Organization', '@id': `${SITE}/#organization`, name: 'Atlantis NDT', url: SITE };

export function trainingGapSchema(p) {
  const url = `${SITE}${p.path}`;
  const faq = {
    '@type': 'FAQPage',
    '@id': `${url}#faq`,
    mainEntity: p.faqs.map((f) => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })),
  };
  const main = p.kind === 'article'
    ? {
        '@type': 'TechArticle',
        '@id': `${url}#article`,
        headline: p.h1,
        description: p.description,
        url,
        datePublished: p.publishedAt,
        dateModified: p.publishedAt,
        author: PERSON,
        publisher: ORG,
        inLanguage: 'en',
      }
    : {
        '@type': 'Course',
        '@id': `${url}#course`,
        name: p.courseName,
        description: p.courseDescription,
        url,
        provider: ORG,
        inLanguage: 'en',
        educationalLevel: 'Professional',
        hasCourseInstance: [{
          '@type': 'CourseInstance',
          courseMode: 'Online',
          ...(p.workload ? { courseWorkload: p.workload } : {}),
          instructor: PERSON,
        }],
      };
  return { '@context': 'https://schema.org', '@graph': [main, faq] };
}

export function trainingGapBody(p) {
  const pub = new Date(`${p.publishedAt}T00:00:00Z`).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });
  return (
    `  <header><nav aria-label="Main Navigation"><a href="/">Home</a><a href="/training">Training</a><a href="/asnt-level-iii-training">ASNT Level III</a><a href="/ndt-training-online">Online NDT Training</a><a href="/contact">Contact</a></nav></header>\n` +
    `  <main>\n    <h1>${p.h1}</h1>\n` +
    `    <p class="byline">By <a href="/authors/anoop-rayavarapu">Anoop Rayavarapu</a>, ASNT NDT Level III · Published ${pub}</p>\n` +
    `${p.bodyHtml}\n${p.relatedHtml}\n  </main>`
  );
}

export function trainingGapRoutes() {
  const { pages } = load('src/data/training-gap-pages.json');
  return pages.map((p) => ({
    path: p.path,
    title: p.title,
    description: p.description,
    h1: p.h1,
    canonical: `${SITE}${p.path}`,
    publishedAt: p.publishedAt,
    structuredData: trainingGapSchema(p),
    bodyContent: trainingGapBody(p),
  }));
}

/** Append the inbound exam-prep blocks inside <main> of hubs and practice pages. */
export function applyTrainingGapInbound(routes) {
  const inbound = load('src/data/training-gap-inbound.json');
  const byPath = new Map(routes.filter((r) => r && r.path).map((r) => [r.path, r]));
  const out = { applied: 0, missing: [] };
  for (const [path, html] of Object.entries(inbound)) {
    const r = byPath.get(path);
    if (!r || typeof r.bodyContent !== 'string') { out.missing.push(path); continue; }
    if (r.bodyContent.includes('data-block="exam-prep-inbound"') || r.bodyContent.includes('data-block="exam-prep-by-method"')) continue;
    const i = r.bodyContent.lastIndexOf('</main>');
    const block = `\n${html}\n`;
    r.bodyContent = i >= 0 ? r.bodyContent.slice(0, i) + block + r.bodyContent.slice(i) : r.bodyContent + block;
    out.applied++;
  }
  return out;
}

/** /ndt-training-online: fold the deep section's visible FAQs into its FAQPage schema. */
export function applyOnlineTrainingFaqSchema(routes) {
  const deep = load('src/data/deep-content/ndt-training-online.json');
  const r = routes.find((x) => x && x.path === '/ndt-training-online');
  if (!r || !deep.faqs?.length) return 0;
  const q = deep.faqs.map((f) => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } }));
  const findFaq = (node) => {
    if (!node || typeof node !== 'object') return null;
    if (node['@type'] === 'FAQPage') return node;
    for (const k of ['@graph']) if (Array.isArray(node[k])) for (const n of node[k]) { const f = findFaq(n); if (f) return f; }
    return null;
  };
  let faq = findFaq(r.structuredData);
  if (faq) {
    const have = new Set((faq.mainEntity || []).map((m) => m.name));
    faq.mainEntity = [...(faq.mainEntity || []), ...q.filter((m) => !have.has(m.name))];
  } else {
    faq = { '@type': 'FAQPage', mainEntity: q };
    r.structuredData = r.structuredData
      ? { '@context': 'https://schema.org', '@graph': [r.structuredData, faq] }
      : { '@context': 'https://schema.org', ...faq };
  }
  return faq.mainEntity.length;
}

export function assertNoPricesInTrainingGap() {
  const blob = readFileSync(join(ROOT, 'src/data/training-gap-pages.json'), 'utf-8') +
    readFileSync(join(ROOT, 'src/data/training-gap-inbound.json'), 'utf-8') +
    readFileSync(join(ROOT, 'src/data/deep-content/ndt-training-online.json'), 'utf-8');
  const hits = blob.match(/[$£€₹]\s?\d|\bodoo\b|anu\.anoop485/gi);
  if (hits) throw new Error(`training-gap content contains forbidden strings: ${[...new Set(hits)].join(', ')}`);
}
