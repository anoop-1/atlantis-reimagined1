#!/usr/bin/env node
// Practical NDT city/state pages — wave 3, 2026-11-18 (CLAUDE.md §80).
//
// Owner, 2026-11-18: "expand further cities across all US cities with NDT practical simulation … all NDT methods …
// follow the SOP … compatibility with Browser, PC or VR. Scale it large across all US cities with high quality content
// where potential demand is there, and make sure to list it across all of Middle East cities with high quality
// content 2000+ words."
// Evidence (GSC 28d to 2026-11-14): the 280 existing city/geo pages earn ~13.5 impressions each; simulator queries
// land on the national pages. So US additions are the places that already show NDT demand on the site but had no
// Practical NDT page (31: states and cities with ≥24 impressions across their pages); Middle East additions are every
// Middle East city the site covers without a Practical NDT page (20), per the owner.
//
// Usage: node scripts/add-practical-ndt-cities-2026-11.mjs <dir-with-records>
//   record: { slug, city, region, title, metaDescription, bodyContent, sources }
// Idempotent: a slug already present is replaced in place. Writes
//   src/data/practical-ndt-cities.json        (React layer data; one JSON per city is emitted at build)
//   scripts/practical-ndt-routes.mjs          (crawler routes; publishedAt 2026-11-18 so the saturated-family pass
//                                              does not canonicalise the new pages to the hub)
//   src/pages/practical-ndt-{slug}.tsx        (thin wrappers) + RouteTable.tsx lazy imports and routes
//   src/data/practical-ndt-directory.json     (hub directory: new state groups, new cities, a Middle East group)
//   scripts/content-sources-2026-11-18.json   (writers' sources, not rendered)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { PRACTICAL_CLAIM_RULES, scrubPracticalClaims } from './practical-ndt-claims.mjs';

const DIR = process.argv[2];
if (!DIR || !existsSync(DIR)) { console.error('usage: node scripts/add-practical-ndt-cities-2026-11.mjs <dir>'); process.exit(1); }
const PUBLISHED = '2026-11-18';
const words = (h) => String(h).replace(/<[^>]+>/g, ' ').replace(/&[a-z#0-9]+;/gi, ' ').split(/\s+/).filter(Boolean).length;
const FORBIDDEN = [
  /\$\s?\d/, /\b(?:USD|AED|SAR|QAR|OMR|KWD|BHD)\s?\d/, /\bNAS[ -]?410\b/i,
  /instant scored feedback|adaptive difficulty|five environments/i,
  ...PRACTICAL_CLAIM_RULES.map(([, re]) => re),
  /\b(?:Aramco|ADNOC|SABIC|PDO|KOC|QatarEnergy)[- ]approved\b/i,
  /Atlantis[^.]{0,60}\b(?:ISO 9712|PCN|API (?:510|570|653))\b[^.]{0,40}\btrain/i,
];

const recs = readdirSync(DIR).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(readFileSync(join(DIR, f), 'utf8')));
const errors = [];
for (const r of recs) {
  for (const k of ['slug', 'city', 'region', 'title', 'metaDescription', 'bodyContent']) if (!r[k]) errors.push(`${r.slug}: missing ${k}`);
  const main = (String(r.bodyContent).match(/<main>([\s\S]*)<\/main>/) || [, ''])[1];
  if (words(main) < 2000) errors.push(`${r.slug}: ${words(main)} words in <main>`);
  for (const re of FORBIDDEN) if (re.test(`${r.title} ${r.metaDescription} ${r.bodyContent}`)) errors.push(`${r.slug}: forbidden ${re}`);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

// 1. React data
const citiesPath = 'src/data/practical-ndt-cities.json';
const cities = JSON.parse(readFileSync(citiesPath, 'utf8'));
const idx = new Map(cities.map((c, i) => [c.slug, i]));
for (const r of recs) {
  const row = { slug: r.slug, city: r.city, region: r.region, title: scrubPracticalClaims(r.title), metaDescription: scrubPracticalClaims(r.metaDescription), contentHtml: scrubPracticalClaims(r.bodyContent) };
  if (idx.has(r.slug)) cities[idx.get(r.slug)] = row; else { idx.set(r.slug, cities.length); cities.push(row); }
}
writeFileSync(citiesPath, JSON.stringify(cities));

// 2. Crawler routes
const routesPath = 'scripts/practical-ndt-routes.mjs';
const { PRACTICAL_NDT_ROUTES } = await import(join(process.cwd(), routesPath) + `?t=${Date.now()}`);
const rIdx = new Map(PRACTICAL_NDT_ROUTES.map((r, i) => [r.path, i]));
for (const r of recs) {
  const row = { path: `/practical-ndt-${r.slug}`, title: scrubPracticalClaims(r.title), description: scrubPracticalClaims(r.metaDescription), bodyContent: scrubPracticalClaims(r.bodyContent), publishedAt: PUBLISHED };
  if (rIdx.has(row.path)) PRACTICAL_NDT_ROUTES[rIdx.get(row.path)] = row; else { rIdx.set(row.path, PRACTICAL_NDT_ROUTES.length); PRACTICAL_NDT_ROUTES.push(row); }
}
writeFileSync(routesPath, `// GENERATED by scripts/build-practical-ndt-routes.mjs — do not hand-edit.\n// Source: merged content-agent batch output (waves 1-2, 2026-09-30) + wave 3 (scripts/add-practical-ndt-cities-2026-11.mjs, ${PUBLISHED}), ${PRACTICAL_NDT_ROUTES.length} cities.\nexport const PRACTICAL_NDT_ROUTES = ${JSON.stringify(PRACTICAL_NDT_ROUTES, null, 2)};\n`);

// 3. Wrappers + RouteTable
const pascal = (s) => s.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
let rt = readFileSync('src/RouteTable.tsx', 'utf8');
const nl = rt.includes('\r\n') ? '\r\n' : '\n';
let lazyAdd = '', routeAdd = '';
for (const r of recs) {
  const comp = `PracticalNdt${pascal(r.slug)}`;
  writeFileSync(`src/pages/practical-ndt-${r.slug}.tsx`, `import PracticalNdtCityRoute from '@/components/PracticalNdtCityRoute';\n\nexport default function ${comp}() {\n  return <PracticalNdtCityRoute slug="${r.slug}" />;\n}\n`);
  if (!rt.includes(`import("./pages/practical-ndt-${r.slug}")`)) lazyAdd += `const ${comp} = lazy(() => import("./pages/practical-ndt-${r.slug}"));${nl}`;
  if (!rt.includes(`path="/practical-ndt-${r.slug}"`)) routeAdd += `                  <Route path="/practical-ndt-${r.slug}" element={<${comp} />} />${nl}`;
}
if (lazyAdd) {
  const re = /const PracticalNdt\w+ = lazy\(\(\) => import\("\.\/pages\/practical-ndt-[a-z0-9-]+"\)\);\r?\n/g;
  let last; for (const m of rt.matchAll(re)) last = m;
  rt = rt.slice(0, last.index + last[0].length) + lazyAdd + rt.slice(last.index + last[0].length);
}
if (routeAdd) {
  const re = / *<Route path="\/practical-ndt-[a-z0-9-]+" element=\{<PracticalNdt\w+ \/>\} \/>\r?\n/g;
  let last; for (const m of rt.matchAll(re)) last = m;
  rt = rt.slice(0, last.index + last[0].length) + routeAdd + rt.slice(last.index + last[0].length);
}
writeFileSync('src/RouteTable.tsx', rt);

// 4. Hub directory
const dirPath = 'src/data/practical-ndt-directory.json';
const directory = JSON.parse(readFileSync(dirPath, 'utf8'));
const byState = new Map(directory.filter((g) => g.slug).map((g) => [g.name, g]));
const regionOf = new Map(cities.map((c) => [c.slug, c.region || '']));
const nameOf = new Map(cities.map((c) => [c.slug, c.city]));
const listed = new Set(directory.flatMap((g) => g.cities.map((c) => c.slug)));
const other = directory.find((g) => !g.slug && /North American/.test(g.name));
const newSlugs = new Set(recs.map((r) => r.slug));
// New US state pages become directory groups and collect their existing cities from "More North American cities".
for (const r of recs) {
  if (!/, USA$/.test(r.region) || r.city !== r.region.replace(/, USA$/, '')) continue;
  if (byState.has(r.city)) continue;
  const g = { slug: r.slug, name: r.city, cities: [] };
  if (other) {
    const keep = [];
    for (const c of other.cities) {
      if (regionOf.get(c.slug) === r.region) g.cities.push({ slug: c.slug, city: nameOf.get(c.slug) || c.city });
      else keep.push(c);
    }
    other.cities = keep;
  }
  byState.set(r.city, g);
  directory.splice(directory.indexOf(other), 0, g);
}
// New US cities join their state group (or "More North American cities").
for (const r of recs) {
  if (!/, USA$/.test(r.region) || r.city === r.region.replace(/, USA$/, '') || listed.has(r.slug)) continue;
  const state = r.region.replace(/, USA$/, '');
  const g = byState.get(state === 'District of Columbia' ? '' : state);
  if (g) g.cities.push({ slug: r.slug, city: r.city });
  else if (other) other.cities.push({ slug: r.slug, city: `${r.city}, ${state === 'District of Columbia' ? 'DC' : state}` });
  listed.add(r.slug);
}
// Middle East group: every Middle East city page (existing + new), grouped by country in the label.
const ME = ['United Arab Emirates', 'Saudi Arabia', 'Qatar', 'Oman', 'Bahrain', 'Kuwait', 'Iraq'];
const meCities = cities.filter((c) => ME.some((m) => (c.region || '').includes(m)) && !['uae', 'saudi-arabia', 'qatar', 'oman', 'bahrain', 'kuwait'].includes(c.slug))
  .sort((a, b) => ME.findIndex((m) => a.region.includes(m)) - ME.findIndex((m) => b.region.includes(m)) || a.city.localeCompare(b.city));
let meGroup = directory.find((g) => g.name === 'Middle East');
if (!meGroup) { meGroup = { slug: null, name: 'Middle East', cities: [] }; directory.push(meGroup); }
meGroup.cities = meCities.map((c) => ({ slug: c.slug, city: `${c.city}, ${ME.find((m) => c.region.includes(m)).replace('United Arab Emirates', 'UAE')}` }));
writeFileSync(dirPath, JSON.stringify(directory, null, 1));

// 5. Sources
const srcPath = 'scripts/content-sources-2026-11-18.json';
const sources = existsSync(srcPath) ? JSON.parse(readFileSync(srcPath, 'utf8')) : {};
for (const r of recs) sources[`/practical-ndt-${r.slug}`] = r.sources || [];
writeFileSync(srcPath, JSON.stringify(sources, null, 1));

console.log(`Practical NDT wave 3: ${recs.length} pages (${[...newSlugs].join(', ')}); routes ${PRACTICAL_NDT_ROUTES.length}; directory groups ${directory.length}; Middle East links ${meGroup.cities.length}`);
